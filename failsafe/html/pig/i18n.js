(function() {
	'use strict';
	var storageKey = 'uboot.language';
	var language;
	try { language = localStorage.getItem(storageKey); } catch (e) {}
	try {
		if (window.parent !== window && window.parent.uiLanguage)
			language = window.parent.uiLanguage;
	} catch (e) {}
	if (language !== 'en' && language !== 'zh')
		language = /^zh\b/i.test(navigator.language || '') ? 'zh' : 'en';
	window.uiLanguage = language;
	window.uiText = function(message, values) {
		var catalog = window.uiLanguage === 'en' ? UI_EN : UI_ZH;
		var result = Object.prototype.hasOwnProperty.call(catalog, message) ? catalog[message] : message;
		return result.replace(/\{(\w+)\}/g, function(match, key) {
			return values && Object.prototype.hasOwnProperty.call(values, key) ? values[key] : match;
		});
	};
	window.translatePage = function() {
		document.documentElement.lang = window.uiLanguage === 'zh' ? 'zh-CN' : 'en';
		document.querySelectorAll('[data-i18n]').forEach(function(el) {
			// Only trusted, bundled messages can contain markup.
			el.innerHTML = uiText(el.getAttribute('data-i18n'));
		});
		['title', 'placeholder', 'aria-label'].forEach(function(attr) {
			document.querySelectorAll('[data-i18n-' + attr + ']').forEach(function(el) {
				el.setAttribute(attr, uiText(el.getAttribute('data-i18n-' + attr)));
			});
		});
	};
	window.uiWorkBusy = function() {
		if (window.uiBusy) return true;
		var frame = document.getElementById('content-frame');
		try { return !!(frame && frame.contentWindow.uiBusy); } catch (e) { return false; }
	};
	window.addEventListener('beforeunload', function(event) {
		if (!window.uiWorkBusy()) return;
		event.preventDefault();
		event.returnValue = '';
	});
	window.setUiBusy = function(busy) {
		window.uiBusy = busy;
		try {
			var picker = window.top.document.getElementById('language-picker');
			if (picker) picker.disabled = busy;
			window.top.document.querySelectorAll('.sidebar-nav-item a').forEach(function(link) {
				link.setAttribute('aria-disabled', String(busy));
			});
		} catch (e) {}
	};
	window.changeUiLanguage = function(next) {
		if (next !== 'en' && next !== 'zh') return false;
		var frame = document.getElementById('content-frame');
		try { if (frame && frame.contentWindow.uiBusy) return false; } catch (e) {}
		if (!confirm(uiText('切换语言将重新加载工具页面，未保存的输入会丢失。继续？'))) return false;
		window.uiLanguage = next;
		try { localStorage.setItem(storageKey, next); } catch (e) {}
		translatePage();
		window.dispatchEvent(new Event('uilanguagechange'));
		if (frame) {
			// Reload only after an explicit choice; do not interrupt uploads or backups.
			try { frame.contentWindow.location.reload(); } catch (e) {}
		}
		return true;
	};
	document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
	document.addEventListener('DOMContentLoaded', translatePage);
})();
